                <p>In the Name of Allah, the Entirely Merciful, the Especially Merciful. <strong>1.</strong> When the earth is shaken with its [final] earthquake. <strong>2.</strong> And when the earth throws out all its contents. <strong>3.</strong> And people say: 'What is wrong with it?!' <strong>4.</strong> On that day it will report its news, <strong>5.</strong> Having been inspired by your Lord. <strong>6.</strong> On that day people will proceed in separate groups to be shown their deeds. <strong>7.</strong> So whoever does an atom's weight of good will see it. <strong>8.</strong> And whoever does an atom's weight of evil will see it.</p>
                
                <p><strong>(0-2)</strong> Allah informs us about what will happen on the Day of Rising, "when the earth is violently shaken," convulsing and rocking "with its final quake," flattening all buildings and structures, the mountains crumble and fall, and the hills are flattened. The earth's surface becomes like a barren, level plain on which you see neither dip nor gradient. "And when the earth throws out all its contents" the deceased and treasures lying within her.</p>
                
                <p><strong>(3)</strong> "and people say" when he sees the terror that has stricken it, exclaiming: "What is wrong with it?" what has happened?!</p>
                
                <p><strong>(4-5)</strong> "On that Day it" the earth "will report its news" bearing witness against people for the good and evil they have done on its surface. The earth is one of the witnesses that will be brought forward on the Day of Rising to testify for or against people. That is "because your Lord had inspired her" ordered her to relate what was done on her surface and she will not disobey His command.</p>
                
                <p><strong>(6)</strong> "That day, people will come forward" to the Standing of the Day of Rising for Allah to judge them "in scattered groups" broken, disparate bands "to be shown their deeds" that Allah may show them what they worked of good and evil and that He may show them His recompense.</p>
                
                <p><strong>(7-8)</strong> "Whoever does an atom's weight of good will see it, and whoever does an atom's weight of evil will see it"," this holds true for any good and any evil that was worked: if a person will see even an atoms weight and, moreover, be recompensed for it, then for sure he will see anything greater as well. Allah says, "On the Day that each self finds the good it did, and the evil it did, present there in front of it, it will wish there were an age between it and then, Allah advises you to beware of Him. Allah is Ever-Gentle with His slaves" (3:30)."</p>
                
                <p>This verse then contains strong encouragement towards performing good deeds, even if it be little, and discouragement from working evil even if it seems minor.</p>
                
                
