      <p>As for washing a dead body: The correct opinion is that it does not nullify the ablution. This is the opinion of most of the scholars due to the lack of evidence to prove that. However, if the hand of the one who is washing the dead body accidentally touches the private part of the dead person without a barrier, it is a must to make ablution. Likewise, it is a must not to touch the private parts of the dead person except behind a barrier.</p>

